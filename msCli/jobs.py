"""Pure helpers: time limits, grid expansion, and sbatch script text."""

import itertools
import os
import re
import shlex

import config
from remote import MsError


def parse_time(text):
    """Seconds from HH:MM:SS, D-HH:MM:SS, or a short form such as 90m, 2h, 1d, 1h30m."""
    t = text.strip().lower()
    match = (re.fullmatch(r"(?:([0-9]+)d)?(?:([0-9]+)h)?(?:([0-9]+)m)?(?:([0-9]+)s)?", t)
             or re.fullmatch(r"(?:([0-9]+)-)?([0-9]+):([0-9]+):([0-9]+)", t))
    if not t or not match:
        raise MsError(f"cannot read time limit '{text}'; use HH:MM:SS, D-HH:MM:SS, or 90m / 2h / 1d")
    d, h, m, s = (int(x or 0) for x in match.groups())
    return d * 86400 + h * 3600 + m * 60 + s


def format_time(seconds):
    d, rest = divmod(seconds, 86400)
    h, rest = divmod(rest, 3600)
    m, s = divmod(rest, 60)
    return f"{d}-{h:02d}:{m:02d}:{s:02d}"


def check_time(text, partition):
    """Validate a time limit against the partition's cap; return it in Slurm form."""
    seconds = parse_time(text)
    cap = config.PARTITIONS[partition]["max_seconds"]
    if seconds <= 0:
        raise MsError("time limit must be more than zero")
    if seconds > cap:
        raise MsError(
            f"time limit {format_time(seconds)} is over the {partition} limit of {format_time(cap)}"
        )
    return format_time(seconds)


def expand_grid(spec):
    """'seed=0,1 lr=1e-3,3e-4' -> ['seed=0 lr=1e-3', 'seed=0 lr=3e-4', ...]"""
    keys, value_lists = [], []
    for token in spec.split():
        if "=" not in token:
            raise MsError(f"--grid: '{token}' is not key=value1,value2")
        if re.search(r"[\[\](){}'\"\\$]", token):
            raise MsError(
                f"--grid: '{token}' has brackets or quotes; only plain comma lists are expanded. "
                "Pass that setting after -- instead."
            )
        key, _, values = token.partition("=")
        values = values.split(",")
        if not key or any(v == "" for v in values):
            raise MsError(f"--grid: '{token}' has an empty key or value")
        keys.append(key)
        value_lists.append(values)
    if not keys:
        raise MsError("--grid is empty")
    return [
        " ".join(f"{k}={v}" for k, v in zip(keys, combo))
        for combo in itertools.product(*value_lists)
    ]


def clean_name(text):
    name = re.sub(r"[^A-Za-z0-9_.]+", "-", text).strip("-.")
    return name[:60] or "job"


def default_label(argv):
    for arg in argv:
        if arg.endswith((".py", ".sh")):
            return os.path.splitext(os.path.basename(arg))[0]
    return os.path.basename(argv[0])


def _bash_array(argv):
    return "CMD=( " + " ".join(shlex.quote(a) for a in argv) + " )"


def _header(name, partition, time, output, array=None):
    lines = [
        "#!/bin/bash",
        f"#SBATCH --job-name={name}",
        f"#SBATCH --partition={partition}",
        "#SBATCH --nodes=1",
        f"#SBATCH --time={time}",
        f"#SBATCH --output={output}",
        # Keep the log from before a requeue; Slurm would otherwise start it afresh.
        "#SBATCH --open-mode=append",
    ]
    if array:
        lines.append(f"#SBATCH --array={array}")
    lines.append("# Generated by ms. Resubmit with ms; do not edit.")
    return lines


def _environment(workdir, modules, venv, commit_to):
    """Lines that prepare the node: modules, working directory, virtual environment."""
    q = shlex.quote
    lines = [
        "export PYTHONUNBUFFERED=1",
        # Hugging Face reads its token from this file, so no job ever contains the token itself.
        f"[ -f {q(config.HF_TOKEN_FILE)} ] && export HF_TOKEN_PATH={q(config.HF_TOKEN_FILE)}",
        # `module` is not defined inside a batch job until Lmod is sourced.
        "[ -f /etc/profile.d/lmod.sh ] && source /etc/profile.d/lmod.sh",
    ]
    for module in modules:
        lines.append(
            f"module load {q(module)} || {{ echo {q('ms: module load failed: ' + module)}; exit 2; }}"
        )
    lines.append(
        f"cd {q(workdir)} || {{ echo {q('ms: cannot cd to ' + workdir + ' (run: ms sync)')}; exit 2; }}"
    )
    if venv:
        lines.append(
            f"source {q(venv + '/bin/activate')} || "
            f"{{ echo {q('ms: cannot activate ' + venv)}; exit 2; }}"
        )
    else:
        lines.append("[ -f .venv/bin/activate ] && source .venv/bin/activate")
    lines.append(
        f'git rev-parse HEAD > "{commit_to}/commit.txt" 2>/dev/null || rm -f "{commit_to}/commit.txt"'
    )
    return lines


def job_script(*, name, partition, time, workdir, argv, modules=(), venv=None):
    """One job on one node. The run directory is <runs>/<name>-<jobid>."""
    runs = config.RUNS
    lines = _header(name, partition, time, f"{runs}/{name}-%j/slurm.out")
    lines += [
        f"export MS_RUN_DIR={shlex.quote(runs)}/{name}-$SLURM_JOB_ID",
        'mkdir -p "$MS_RUN_DIR"',
    ]
    lines += _environment(workdir, modules, venv, "$MS_RUN_DIR")
    lines += [
        'echo "ms: start $(date -Is) host=$(hostname) restart=${SLURM_RESTART_COUNT:-0}"',
        _bash_array(argv),
        '"${CMD[@]}"',
        "rc=$?",
        'echo "ms: exit $rc $(date -Is)"',
        "exit $rc",
    ]
    return "\n".join(lines) + "\n"


_SWEEP_BODY = r"""
ms_task() {
  local i=$1 pad d a line rc
  local args=() extra=()
  pad=$(printf '%04d' "$i")
  d=$MS_SWEEP_DIR/task-$pad
  # A finished task is never repeated, so requeues and retries cost nothing.
  [ -e "$MS_SWEEP_DIR/.ms/done/$pad" ] && return 0
  mkdir -p "$d"
  rm -f "$MS_SWEEP_DIR/.ms/failed/$pad"
  : > "$MS_SWEEP_DIR/.ms/started/$pad"
  for a in "${CMD[@]}"; do
    a=${a//"{i}"/$i}
    a=${a//"{n}"/$MS_N}
    args+=("$a")
  done
  if [ -f "$MS_SWEEP_DIR/tasks.txt" ]; then
    line=$(sed -n "$((i + 1))p" "$MS_SWEEP_DIR/tasks.txt")
    read -r -a extra <<< "$line"
    args+=("${extra[@]}")
  fi
  (
    export MS_RUN_DIR=$d MS_TASK_ID=$i MS_NUM_TASKS=$MS_N
    echo "ms: start $(date -Is) host=$(hostname) task=$i restart=${SLURM_RESTART_COUNT:-0}"
    "${args[@]}"
    rc=$?
    echo "ms: exit $rc $(date -Is)"
    exit $rc
  ) >> "$d/task.log" 2>&1
  rc=$?
  if [ "$rc" -eq 0 ]; then
    : > "$MS_SWEEP_DIR/.ms/done/$pad"
  else
    echo "$rc" > "$MS_SWEEP_DIR/.ms/failed/$pad"
  fi
  return "$rc"
}

first=$(( SLURM_ARRAY_TASK_ID * MS_P ))
last=$(( first + MS_P - 1 ))
[ "$last" -ge "$MS_N" ] && last=$(( MS_N - 1 ))
echo "ms: node $(hostname) runs tasks $first to $last, restart=${SLURM_RESTART_COUNT:-0}"
pids=()
for i in $(seq "$first" "$last"); do
  ms_task "$i" &
  pids+=("$!")
done
fail=0
for p in "${pids[@]}"; do
  wait "$p" || fail=1
done
echo "ms: node done, failures=$fail"
exit $fail
"""


def sweep_script(*, name, partition, time, workdir, argv, ntasks, per_node, modules=(), venv=None):
    """N independent tasks as one job array, `per_node` tasks to a node.

    Sweep directory: <runs>/<name>-<arrayjobid>/ with task-0000/, task-0001/, ...
    """
    runs = config.RUNS
    elements = -(-ntasks // per_node)
    cap = config.PARTITIONS[partition]["max_running"]
    lines = _header(
        name, partition, time, f"{runs}/{name}-%A/slurm-%a.out", array=f"0-{elements - 1}%{cap}"
    )
    lines += [
        f"MS_SWEEP_DIR={shlex.quote(runs)}/{name}-$SLURM_ARRAY_JOB_ID",
        f"MS_N={ntasks}",
        f"MS_P={per_node}",
    ]
    lines += _environment(workdir, modules, venv, "$MS_SWEEP_DIR")
    lines.append(_bash_array(argv))
    return "\n".join(lines) + "\n" + _SWEEP_BODY
